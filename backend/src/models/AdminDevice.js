'use strict';

const mongoose = require('mongoose');

const {
  DEVICE_PLATFORMS,
} = require('../constants/Notification');

const adminDeviceSchema = new mongoose.Schema(
  {
    admin: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },

    token: {
      type: String,
      required: true,
      trim: true,
    },

    platform: {
      type: String,
      enum: Object.values(DEVICE_PLATFORMS),
      default: DEVICE_PLATFORMS.WEB,
    },

    deviceName: {
      type: String,
      trim: true,
      maxlength: 120,
      default: null,
    },

    /*
     * Optional stable browser/device identifier
     * generated by frontend.
     */
    deviceId: {
      type: String,
      trim: true,
      maxlength: 200,
      default: null,
    },

    isActive: {
      type: Boolean,
      default: true,
      index: true,
    },

    lastSeenAt: {
      type: Date,
      default: Date.now,
    },

    invalidatedAt: {
      type: Date,
      default: null,
    },

    invalidReason: {
      type: String,
      trim: true,
      maxlength: 500,
      default: null,
    },
  },
  {
    timestamps: true,
  },
);

/*
 * One FCM token must belong to only one
 * active registration record.
 */
adminDeviceSchema.index(
  {
    token: 1,
  },
  {
    unique: true,
  },
);

adminDeviceSchema.index({
  admin: 1,
  isActive: 1,
  updatedAt: -1,
});

adminDeviceSchema.index(
  {
    admin: 1,
    deviceId: 1,
  },
  {
    unique: true,

    partialFilterExpression: {
      deviceId: {
        $type: 'string',
      },
    },
  },
);

module.exports = mongoose.model(
  'AdminDevice',
  adminDeviceSchema,
);