'use strict';

const { z } = require('zod');

const {
  NOTIFICATION_TYPES,
  DEVICE_PLATFORMS,
} = require('../constants/Notification');

/*
|--------------------------------------------------------------------------
| Common
|--------------------------------------------------------------------------
*/

const objectIdSchema = z
  .string()
  .regex(
    /^[0-9a-fA-F]{24}$/,
    'Invalid MongoDB ObjectId',
  );

/*
|--------------------------------------------------------------------------
| Notification List
|--------------------------------------------------------------------------
*/

const notificationListQuery = z
  .object({
    page: z.coerce
      .number()
      .int()
      .min(1)
      .default(1),

    limit: z.coerce
      .number()
      .int()
      .min(1)
      .max(100)
      .default(20),

    unreadOnly: z
      .enum(['true', 'false'])
      .transform(
        (value) =>
          value === 'true',
      )
      .default('false'),

    type: z
      .enum(
        Object.values(
          NOTIFICATION_TYPES,
        ),
      )
      .optional(),
  })
  .strict();

/*
|--------------------------------------------------------------------------
| Notification ID
|--------------------------------------------------------------------------
*/

const notificationIdParams = z
  .object({
    notificationId:
      objectIdSchema,
  })
  .strict();

/*
|--------------------------------------------------------------------------
| Register Admin Device
|--------------------------------------------------------------------------
*/

const registerDeviceBody = z
  .object({
    token: z
      .string()
      .trim()
      .min(
        20,
        'FCM token is required',
      )
      .max(4096),

    platform: z
      .enum(
        Object.values(
          DEVICE_PLATFORMS,
        ),
      )
      .default(
        DEVICE_PLATFORMS.WEB,
      ),

    deviceName: z
      .string()
      .trim()
      .min(1)
      .max(120)
      .optional(),

    /*
     * Stable identifier generated by frontend.
     *
     * Example:
     * localStorage UUID for browser installation.
     */
    deviceId: z
      .string()
      .trim()
      .min(1)
      .max(200)
      .optional(),
  })
  .strict();

/*
|--------------------------------------------------------------------------
| Remove Device
|--------------------------------------------------------------------------
*/

const deviceIdParams = z
  .object({
    deviceId:
      objectIdSchema,
  })
  .strict();
const unregisterDeviceBody = z
  .object({
    token: z
      .string()
      .trim()
      .min(20)
      .max(4096),
  })
  .strict();
module.exports = {
  notificationListQuery,
  notificationIdParams,
  unregisterDeviceBody,
  registerDeviceBody,
  deviceIdParams,
};