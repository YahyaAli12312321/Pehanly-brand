'use strict';

/*
 * Prints every mounted route as a Markdown table (method, path, access).
 *   node scripts/list-routes.js > docs/API_ROUTES.md
 *
 * "access" is derived from the path convention, not guessed per handler:
 *   /admin/staff, /admin/notifications, /admin/devices, /admin/audit-logs   owner only
 *   /admin/*                                              staff with the module permission (owner always)
 *   everything else                                       see docs/API.md (public / signed-in / owner of the resource)
 * Reads the live Express router, so it cannot drift from the code.
 */

process.env.NODE_ENV = process.env.NODE_ENV || 'test';
process.env.CORS_ORIGINS = process.env.CORS_ORIGINS || 'http://localhost:5173';
process.env.CLIENT_URL = process.env.CLIENT_URL || 'http://localhost:5173';
process.env.JWT_SECRET = process.env.JWT_SECRET || 'route-listing-only-route-listing-only-1234';
process.env.MONGODB_URI = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/route_listing';
process.env.MONGODB_TEST_URI = process.env.MONGODB_TEST_URI || 'mongodb://127.0.0.1:27017/route_listing_test';

const { createApp, API_PREFIX } = require('../src/app');

function pathFromLayer(layer) {
  if (layer.regexp && layer.regexp.fast_slash) return '';

  const match = layer.regexp
    .toString()
    .replace('\\/?', '')
    .replace('(?=\\/|$)', '$')
    .match(/^\/\^((?:\\[.*+?^${}()|[\]\\/]|[^.*+?^${}()|[\]\\/])*)\$\//);

  return match ? match[1].replace(/\\(.)/g, '$1') : '';
}

function walk(stack, prefix, out) {
  for (const layer of stack) {
    if (layer.route) {
      for (const method of Object.keys(layer.route.methods)) {
        out.push({ method: method.toUpperCase(), path: prefix + layer.route.path });
      }
    } else if (layer.name === 'router' && layer.handle.stack) {
      walk(layer.handle.stack, prefix + pathFromLayer(layer), out);
    }
  }
}

function access(path) {
  const p = path.replace(API_PREFIX, '');

  if (/^\/admin\/(staff|notifications|devices|audit-logs)(\/|$)/.test(p)) return 'owner only';
  if (p.startsWith('/admin')) return 'staff (module permission)';
  return 'see API.md';
}

const routes = [];
walk(createApp()._router.stack, '', routes);

const unique = [...new Map(routes.map((r) => [`${r.method} ${r.path}`, r])).values()].sort(
  (a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method),
);

console.log('# Route index\n');
console.log(`Generated by \`node scripts/list-routes.js\` - ${unique.length} routes.\n`);
console.log('| Method | Path | Access |');
console.log('| --- | --- | --- |');

for (const r of unique) {
  console.log(`| ${r.method} | \`${r.path}\` | ${access(r.path)} |`);
}

process.exit(0);
